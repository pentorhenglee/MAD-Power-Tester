/*
 * link.h - สายคุยระหว่างบอร์ด A กับบอร์ด B (USART6 115200 8N1)  ไฟล์นี้เหมือนกันทั้งสองบอร์ด
 *
 * ทำไมต้องมี: ด่านกรี๊ดกับด่านต่อยใช้เซนเซอร์ที่อยู่บอร์ด B
 *             แต่สมองของเกม (game.c) อยู่บอร์ด A
 *             A จึงสั่งให้ B ลงมือ แล้วรอ B ส่งคะแนนกลับมา
 *
 * ข้อความละหนึ่งบรรทัด จบด้วย '\n' เป็นตัวอักษรอ่านออกทั้งหมด
 * จะได้เสียบสาย USB-TTL ดูด้วยตาได้ตอนหาบั๊ก
 *
 *   A  ->  B
 *     S<n>        เริ่มด่านเบอร์ n   (1 = กรี๊ด, 3 = ต่อย)
 *     P<n>        เล่นเสียงไฟล์ n หนึ่งรอบ ตัดเพลงที่เล่นอยู่ทันที (1-11 ดูเบอร์ใน sound.h)
 *     Q<n>        เล่นไฟล์ n วนไม่หยุด เริ่มหลังเพลงที่เล่นอยู่จบ จนกว่าจะสั่ง X หรือ P
 *     X           หยุดเสียง
 *     L<n>        โหมดไฟ WS2812B    (0 = ดับ, 1 = รอผู้เล่น, 2 = เล่นอยู่, 3 = ฉลอง · 4 = ห้ามตะโกน บอร์ด B ตั้งเองในด่านกรี๊ด)
 *     A<best>     ให้จอ B ขึ้นหน้า ATTRACT พร้อมสถิติสูงสุด (-1 = ยังไม่มีใครเล่น ขึ้น "---")
 *                 (ถ้าจอ B หรี่อยู่ก็เปิดไฟจอเต็มด้วย)
 *     Z           เกมหลับ ให้จอ B หรี่ไฟจอตามจอ A (A S W H F ทำให้ไฟจอกลับมาเต็ม)
 *     F<รวม> <ด่าน1> <ด่าน2> <ด่าน3> <สถิติ> <ทำลายสถิติ 0/1>
 *                 ให้จอ B ขึ้นหน้าสรุปรวม คนมุงจะได้เห็นคะแนนบนจอใหญ่ (A ส่งซ้ำทุก 1.5 วิ ตลอดที่หน้าสรุปค้างอยู่)
 *     W<หน้า>     ให้จอ B ขึ้นหน้าเดียวกับจอ A (เลขตาม screen_id_t) เช่นหน้าอธิบายด่าน 3-2-1
 *     H<หน้า> <s> ให้จอ B ขึ้นหน้าคะแนนด่านพร้อมคะแนน s
 *     M<ติด> <คะแนน> <ms> <ผิด>  ด่านตบปุ่มสด ~10 ครั้ง/วิ: mask ดวงที่ติด · คะแนนสด · เวลาเหลือ · mask ดวงที่ตบผิด
 *                 mask = บิต i คือปุ่ม i (0-8) เช่น M273 120 15300 0 = ดวง 0 4 8 ติด ไม่มีดวงผิด
 *                 (W H M จอ B ทำตามเฉพาะตอนไม่มีด่านของ B รันอยู่ ด่านของ B วาดจอเอง)
 *
 *   B  ->  A
 *     K<n>        ได้คำสั่ง S<n> แล้ว (A ไม่ได้ K ภายใน 0.8 วิ ส่ง S ซ้ำ สูงสุด 3 ครั้ง)
 *     D<n> <s>    ด่าน n จบแล้ว ได้ s คะแนน (0-1000) ส่งซ้ำทุก 0.5 วิ สูงสุด 6 ครั้ง จนกว่าจะได้ยินอะไรจาก A
 *     R           บอร์ด B พร้อมแล้ว (ส่งตอนเพิ่งบูต)
 *
 * ตัวอย่างหนึ่งเกม
 *   A->B  A2830     จอ B ขึ้นหน้าเรียกแขก
 *   A->B  P3        เล่นเสียง "Ready... Fight!"
 *   A->B  L2        ไฟเปลี่ยนเป็นโหมดเล่น
 *   A->B  S1        เริ่มด่านกรี๊ด (B เล่นคำเกริ่น นับเงียบ วัดเสียงพื้น แล้วเล่น 10 วิ เอง)
 *   B->A  D1 668    ด่านกรี๊ดจบ ได้ 668
 *   A->B  S3        เริ่มด่านต่อย
 *   B->A  D3 795
 *   A->B  F2198 668 735 795 2830 0
 *
 * บรรทัดยาวสุด 95 ตัวอักษร (LINE_MAX ใน link.c) ฝั่งที่อ่านต้องมีบัฟเฟอร์ขนาดเท่านี้
 */
#ifndef LINK_H
#define LINK_H

void Link_Init(void);                  /* เปิดรับข้อมูลแบบอินเทอร์รัพต์ */
void Link_Send(const char *line);      /* ส่งหนึ่งบรรทัด เติม '\n' ให้เอง */

/* อ่านบรรทัดเก่าสุดที่ยังไม่ได้อ่าน คืน 1 ถ้ามี คืน 0 ถ้ายังไม่มีอะไรเข้ามา
   เก็บค้างได้ 7 บรรทัด ต้องเรียกบ่อย ๆ ในลูปหลัก */
int  Link_Receive(char *buf, int size);

/* รับไบต์ล่าสุดมานานกี่ ms แล้ว (ตอนนี้ไม่มีใครเรียก ไฟเส้นเปลี่ยนไปใช้ DMA ไม่ต้องรอสายเงียบแล้ว) */
#include <stdint.h>
uint32_t Link_IdleMs(void);

#endif
